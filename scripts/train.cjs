// Headless evolution; the included demo policy is reproducible from this script.
const fs = require("node:fs");
const path = require("node:path");
const E = require("../demo/engine.js");
const started = performance.now();
let evaluatedGames = 0;
let simulatedMoves = 0;
const rng = E.random(20190721);
const POPULATION = 64;
const GENERATIONS = 60;
const TRAIN_SEEDS = [31, 137, 911];
const VALIDATION_SEEDS = [7, 2026, 8675309, 410, 709];
function normal() {
  return Math.sqrt(-2 * Math.log(Math.max(1e-12, rng()))) * Math.cos(2 * Math.PI * rng());
}
const baseline = E.heuristicWeights();
function mutate(weights, sigma, probability = .12) {
  return weights.map((w) => w + (rng() < probability ? normal() * sigma : 0));
}
let population = Array.from({ length: POPULATION }, (_, i) => i === 0
  ? [...baseline] : mutate(baseline, i < 16 ? .8 : 2.5, .45));
let best;
const history = [];
for (let generation = 0; generation < GENERATIONS; generation++) {
  const ranked = population.map((weights) => {
    const runs = TRAIN_SEEDS.map((seed) => E.simulate(weights, { seed, maxMoves: 1200, hungerLimit: 180 }, false));
    evaluatedGames += runs.length;
    simulatedMoves += runs.reduce((sum, run) => sum + run.moves, 0);
    return { weights, fitness: runs.reduce((n, r) => n + r.fitness, 0) / runs.length,
      food: runs.reduce((n, r) => n + r.score, 0) / runs.length };
  }).sort((a, b) => b.fitness - a.fitness);
  best = ranked[0];
  history.push({ generation: generation + 1, fitness: Number(best.fitness.toFixed(3)),
    meanFood: Number(best.food.toFixed(3)) });
  if ((generation + 1) % 10 === 0) console.log(`Generation ${generation + 1}: mean food ${best.food.toFixed(1)}`);
  const parents = ranked.slice(0, 12);
  population = parents.slice(0, 4).map((p) => [...p.weights]);
  while (population.length < POPULATION) {
    const a = parents[Math.floor(rng() * parents.length)].weights;
    const b = parents[Math.floor(rng() * parents.length)].weights;
    const child = a.map((value, i) => rng() < .5 ? value : b[i]);
    population.push(mutate(child, generation < 30 ? .55 : .25));
  }
}
const finalWeights = best.weights.map((w) => Number(w.toPrecision(12)));
const model = {
  name: "Evolved demo network", architecture: E.SHAPE, seed: 20190721,
  method: "Genetic evolution from a documented heuristic initialization",
  population: POPULATION, generations: GENERATIONS, trainSeeds: TRAIN_SEEDS,
  evaluatedGames, simulatedMoves,
  validation: VALIDATION_SEEDS.map((seed) => {
    const run = E.simulate(finalWeights, { seed, maxMoves: 2000 }, false);
    return { seed, score: run.score, moves: run.moves, reason: run.reason };
  }),
  history,
  weights: finalWeights,
};
fs.mkdirSync(path.resolve(__dirname, "../demo"), { recursive: true });
fs.writeFileSync(path.resolve(__dirname, "../demo/policy.js"),
  `// Generated by scripts/train.cjs; no original trained weights were present in the repository.\n` +
  `(function(root){const policy=${JSON.stringify(model)};if(typeof module==="object"&&module.exports)module.exports=policy;else root.SnakePolicy=policy;})(globalThis);\n`);
console.log(JSON.stringify(model.validation, null, 2));
console.log(`Headless training: ${evaluatedGames} games, ${simulatedMoves} moves, ${((performance.now() - started) / 1000).toFixed(2)} seconds. No rendering or frame-rate waits.`);
